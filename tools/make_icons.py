#!/usr/bin/env python3
"""
Build the app icons from the supplied TreeMapper artwork.

Inputs : tools/source_icon.png  (white glyph on the brand green square)
Outputs: resources/drawables/launcher_icon.png  128x128, as supplied
         resources/drawables/mark_w{64,96,130}.png  glyph only, white on transparent
         resources-<product>/drawables/  exact size launcher icons for the
         handhelds, whose launcher slots are not square

The app draws the white glyph, since every screen is black. Three fixed sizes
are shipped rather than one scaled resource: the resource compiler's scaleX
attribute takes a pixel format, not a fraction of the screen, so Layout.mc picks
the right size at runtime from the screen width instead.
"""
import os
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "resources", "drawables")
SRC = os.path.join(HERE, "source_icon.png")

BRAND = (0x00, 0x7A, 0x49)

#: Exact launcher icon sizes for the handhelds, as width x height.
#:
#: Three of the four ask for 38x33, which is not square. Letting the resource
#: compiler scale the 128x128 artwork into that slot squashes the glyph by
#: about 13 percent horizontally, and the handhelds are the priority hardware
#: for this app, so each gets its own icon instead.
#:
#: The watches are deliberately absent. Their slots are square, so the
#: downscale from 128 is clean and the base icon is the right answer there.
#:
#: These numbers come from launcherIcon in each device's compiler.json in the
#: SDK device database:
#:   ~/Library/Application Support/Garmin/ConnectIQ/Devices/<id>/compiler.json
#: Read them from there before adding a product. Guessing produces an icon
#: that builds and looks wrong on the wrist.
DEVICE_ICONS = {
    "gpsmaph1":   (32, 32),
    "etrextouch": (38, 33),
    "gpsmap86":   (38, 33),
    "gpsmap66":   (38, 33),
}

DEVICE_DRAWABLES_XML = """<resources>
    <!--
      Generated by tools/make_icons.py. Do not hand edit.

      This overrides Drawables.LauncherIcon for this product only, at the exact
      size its launcher slot asks for. Everything else, including the mark
      bitmaps, still comes from resources/drawables.
    -->
    <bitmap id="LauncherIcon" filename="launcher_icon.png" />
</resources>
"""


def glyph_alpha(img):
    """Return an alpha mask where the white artwork is opaque.

    The source is a white glyph on a solid green field, so whiteness is a
    clean proxy for coverage and it keeps the anti aliased edges intact.
    """
    rgb = img.convert("RGB")
    w, h = rgb.size
    alpha = Image.new("L", (w, h))
    src = rgb.load()
    dst = alpha.load()
    for y in range(h):
        for x in range(w):
            r, g, b = src[x, y]
            # distance from the brand green toward white, 0..1
            t = min(r, g, b) / 255.0
            # push the midpoint so the field stays fully transparent
            v = (t - 0.10) / 0.90
            dst[x, y] = max(0, min(255, int(v * 255)))
    return alpha


def device_icon(src, width, height):
    """The artwork at a product's exact launcher size, without distortion.

    The glyph stays square. When the slot is wider than it is tall the extra
    width is filled with the brand green, so the tile still covers its slot
    and the icon reads as deliberate rather than letterboxed. Padding with
    green rather than transparency also keeps this independent of whether a
    given product blends alpha in its launcher.
    """
    side = min(width, height)
    tile = src.convert("RGB").resize((side, side), Image.LANCZOS)
    if width == side and height == side:
        return tile
    out = Image.new("RGB", (width, height), BRAND)
    out.paste(tile, ((width - side) // 2, (height - side) // 2))
    return out


def write_device_icons(src):
    """Write resources-<product>/drawables for every product in DEVICE_ICONS.

    The folders are wired up in monkey.jungle with a resourcePath line each.
    A folder written here without that line is silently ignored by the build.
    """
    root = os.path.join(HERE, "..")
    for product, (width, height) in sorted(DEVICE_ICONS.items()):
        folder = os.path.join(root, "resources-%s" % product, "drawables")
        if not os.path.isdir(folder):
            os.makedirs(folder)
        device_icon(src, width, height).save(
            os.path.join(folder, "launcher_icon.png"))
        with open(os.path.join(folder, "drawables.xml"), "w") as f:
            f.write(DEVICE_DRAWABLES_XML)
        print("  %-12s %dx%d" % (product, width, height))


def tint(alpha, colour, size):
    out = Image.new("RGBA", alpha.size, colour + (0,))
    out.putalpha(alpha)
    return out.resize((size, size), Image.LANCZOS)


def main():
    if not os.path.exists(SRC):
        raise SystemExit("missing %s" % SRC)

    src = Image.open(SRC)
    # square it, in case the export carried a stray column
    side = min(src.size)
    src = src.crop((0, 0, side, side))

    src.convert("RGB").resize((128, 128), Image.LANCZOS).save(
        os.path.join(OUT, "launcher_icon.png"))

    write_device_icons(src)

    a = glyph_alpha(src)
    # Roughly 30 percent of screen width for the three screen size bands.
    for size in (64, 96, 130):
        tint(a, (255, 255, 255), size).save(
            os.path.join(OUT, "mark_w%d.png" % size))
    # Kept full size for the preview renderer.
    tint(a, (255, 255, 255), 320).save(os.path.join(OUT, "..", "..",
                                                    "tools", "mark_full.png"))
    print("icons written")


if __name__ == "__main__":
    main()
